#include <Utils/KeyCodes.h>

#include <GLFW/glfw3.h>
#include <gtest/gtest.h>

TEST(KeyCodesTest, keyboard_codes_match_glfw)
{
	EXPECT_EQ(DL_KEY_SPACE, GLFW_KEY_SPACE);
	EXPECT_EQ(DL_KEY_0, GLFW_KEY_0);
	EXPECT_EQ(DL_KEY_9, GLFW_KEY_9);
	EXPECT_EQ(DL_KEY_A, GLFW_KEY_A);
	EXPECT_EQ(DL_KEY_Z, GLFW_KEY_Z);
	EXPECT_EQ(DL_KEY_ESCAPE, GLFW_KEY_ESCAPE);
	EXPECT_EQ(DL_KEY_ENTER, GLFW_KEY_ENTER);
	EXPECT_EQ(DL_KEY_TAB, GLFW_KEY_TAB);
	EXPECT_EQ(DL_KEY_F1, GLFW_KEY_F1);
	EXPECT_EQ(DL_KEY_F12, GLFW_KEY_F12);
	EXPECT_EQ(DL_KEY_LEFT_SHIFT, GLFW_KEY_LEFT_SHIFT);
	EXPECT_EQ(DL_KEY_LEFT_CONTROL, GLFW_KEY_LEFT_CONTROL);
	EXPECT_EQ(DL_KEY_MENU, GLFW_KEY_MENU);
}

TEST(KeyCodesTest, mouse_codes_match_glfw)
{
	EXPECT_EQ(DL_MOUSE_BUTTON_LEFT, GLFW_MOUSE_BUTTON_LEFT);
	EXPECT_EQ(DL_MOUSE_BUTTON_RIGHT, GLFW_MOUSE_BUTTON_RIGHT);
	EXPECT_EQ(DL_MOUSE_BUTTON_MIDDLE, GLFW_MOUSE_BUTTON_MIDDLE);
	EXPECT_EQ(DL_MOUSE_BUTTON_LAST, GLFW_MOUSE_BUTTON_LAST);
}

TEST(KeyCodesTest, gamepad_codes_match_glfw)
{
	EXPECT_EQ(DL_GAMEPAD_BUTTON_A, GLFW_GAMEPAD_BUTTON_A);
	EXPECT_EQ(DL_GAMEPAD_BUTTON_START, GLFW_GAMEPAD_BUTTON_START);
	EXPECT_EQ(DL_GAMEPAD_BUTTON_LAST, GLFW_GAMEPAD_BUTTON_LAST);
	EXPECT_EQ(DL_GAMEPAD_AXIS_LEFT_X, GLFW_GAMEPAD_AXIS_LEFT_X);
	EXPECT_EQ(DL_GAMEPAD_AXIS_RIGHT_TRIGGER, GLFW_GAMEPAD_AXIS_RIGHT_TRIGGER);
	EXPECT_EQ(DL_GAMEPAD_AXIS_LAST, GLFW_GAMEPAD_AXIS_LAST);
}

TEST(KeyCodesTest, joystick_codes_match_glfw)
{
	EXPECT_EQ(DL_JOYSTICK_1, GLFW_JOYSTICK_1);
	EXPECT_EQ(DL_JOYSTICK_LAST, GLFW_JOYSTICK_LAST);
}
